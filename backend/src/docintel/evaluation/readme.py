"""The README's evaluation table, generated from the committed reports (Phase 10, ADR-070).

`docintel evaluation readme` replaces the text between the two markers with the provenance of
the reports (which commit produced which suite) and one row per headline; `--check` fails when
the README differs, which CI runs. Only full runs from clean checkouts qualify: a quick report or
one from uncommitted code ("+dirty") is refused, so the README never shows a number that cannot
be reproduced from a commit.
"""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Mapping

from docintel.evaluation.headlines import HEADLINES, NOT_MEASURED, Payload

BEGIN = "<!-- evaluation:begin - generated by `docintel evaluation readme`, do not edit -->"
END = "<!-- evaluation:end -->"
REPORTS_LINK = "evaluation/reports"


class ReadmeError(ValueError):
    """The reports cannot back the README (missing, quick or uncommitted), or no markers."""


def _suites() -> list[str]:
    ordered: list[str] = []
    for headline in HEADLINES:
        if headline.suite not in ordered:
            ordered.append(headline.suite)
    return ordered


def _check(reports: Mapping[str, Payload]) -> None:
    problems = []
    for suite in _suites():
        report = reports.get(suite)
        if report is None:
            problems.append(f"{suite}: no report")
            continue
        revision = report.get("git_revision")
        if report.get("quick"):
            problems.append(f"{suite}: a quick run (README numbers come from full runs)")
        if not revision or str(revision).endswith("+dirty"):
            problems.append(f"{suite}: not from a clean checkout ({revision or 'unknown commit'})")
    if problems:
        raise ReadmeError("; ".join(problems))


def _provenance(reports: Mapping[str, Payload]) -> str:
    by_commit: dict[str, list[str]] = defaultdict(list)
    for suite in _suites():
        by_commit[str(reports[suite]["git_revision"])[:7]].append(suite)
    parts = [f"{', '.join(suites)} at `{commit}`" for commit, suites in by_commit.items()]
    return (
        "Every number in this table is generated from the committed reports by "
        "`docintel evaluation readme` (CI checks it is current); the reports come from "
        f"`make evaluate` on clean checkouts: {'; '.join(parts)}."
    )


def render_block(reports: Mapping[str, Payload]) -> str:
    _check(reports)
    lines = [
        BEGIN,
        _provenance(reports),
        "",
        "| Metric | Value | Report |",
        "|---|---|---|",
    ]
    for headline in HEADLINES:
        try:
            value = headline.render(reports[headline.suite])
        except (KeyError, TypeError, ValueError, StopIteration) as exc:
            msg = f"{headline.suite}: '{headline.label}' cannot be rendered ({exc!r})"
            raise ReadmeError(msg) from exc
        link = f"[{headline.suite}]({REPORTS_LINK}/{headline.suite}.md)"
        lines.append(f"| {headline.label} | {value} | {link} |")
    for missing in NOT_MEASURED:
        lines.append(f"| {missing.label} | Not yet measured ({missing.reason}) | |")
    lines.append(END)
    return "\n".join(lines)


def update_readme(text: str, block: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        msg = "the README needs exactly one pair of evaluation markers"
        raise ReadmeError(msg)
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    if end < start:
        msg = "the evaluation end marker comes before the begin marker"
        raise ReadmeError(msg)
    return text[:start] + block + text[end:]
