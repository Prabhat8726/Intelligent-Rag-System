def headlines_for(suite: str, payload: Payload) -> list[tuple[str, str | None]]:
    """(label, value) of a suite's rows; None where this report lacks the metric (a quick or
    an older report)."""
    rows: list[tuple[str, str | None]] = []
    for headline in HEADLINES:
        if headline.suite != suite:
            continue
        try:
            value: str | None = headline.render(payload)
        except (KeyError, TypeError, ValueError, StopIteration):
            value = None
        rows.append((headline.label, value))
    return rows
