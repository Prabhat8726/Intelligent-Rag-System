"""Headline metrics: the numbers the README and the web app show, rendered from reports.

Every row is a function of one suite's report, so no number is typed by hand (ADR-070): the
README block between its markers is generated by `docintel evaluation readme`, CI checks that
it matches the committed reports, and the evaluations API shows the same rows per suite. A row
whose report lacks a metric raises: a renamed metric must not leave a stale number behind.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Any

Payload = Mapping[str, Any]  # a report's JSON: suite, metrics, dataset, config, ...


@dataclass(frozen=True, slots=True)
class Headline:
    suite: str
    label: str
    render: Callable[[Payload], str]


@dataclass(frozen=True, slots=True)
class NotMeasured:
    label: str
    reason: str


def pct(value: float | None, digits: int = 1) -> str:
    if value is None:
        return "n/a"
    if value in (0, 1):
        return f"{value * 100:.0f}%"
    return f"{value * 100:.{digits}f}%"


def dec(value: float | None, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value:,.0f} ms"


def seconds(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f} s"


def _m(payload: Payload, *keys: str) -> Any:
    value: Any = payload["metrics"]
    for key in keys:
        value = value[key]
    return value


# ------------------------------------------------------------------------------ OCR
def _ocr(degradation: str) -> Callable[[Payload], str]:
    def render(p: Payload) -> str:
        run = _m(p, degradation, "default")
        return f"{pct(run['cer']['mean'])} / {pct(run['wer']['mean'])} ({run['pages']} pages)"

    return render


def _ocr_rotation(p: Payload) -> str:
    skew, sideways = _m(p, "skew_3deg", "default"), _m(p, "sideways_90deg", "default")
    return (
        f"{pct(skew['cer']['mean'])} / {pct(skew['wer']['mean'])} · "
        f"{pct(sideways['cer']['mean'])} / {pct(sideways['wer']['mean'])}"
    )


def _ocr_ablation(p: Payload) -> str:
    upscale, deskew = _m(p, "low_res_100dpi", "no_upscale"), _m(p, "skew_3deg", "no_deskew")
    with_upscale, with_deskew = _m(p, "low_res_100dpi", "default"), _m(p, "skew_3deg", "default")
    return (
        f"100 DPI without upscaling {pct(upscale['cer']['mean'])} / "
        f"{pct(upscale['wer']['mean'])} (with: {pct(with_upscale['cer']['mean'])} / "
        f"{pct(with_upscale['wer']['mean'])}) · 3° skew without deskew "
        f"{pct(deskew['cer']['mean'])} / {pct(deskew['wer']['mean'])} (with: "
        f"{pct(with_deskew['cer']['mean'])} / {pct(with_deskew['wer']['mean'])})"
    )


# ------------------------------------------------------------------------------ classification
def _classification_rendered(p: Payload) -> str:
    run = _m(p, "rendered/all")
    return f"{pct(run['accuracy'])} / {dec(run['macro_f1'])} (n = {run['n']})"


def _classification_prefix(p: Payload) -> str:
    run = _m(p, "text/first_300_chars")
    return (
        f"{pct(run['accuracy'])} (n = {run['n']}); "
        f"{pct(run['routing']['error_rate_in_auto_bucket'])} error in the auto-accepted bucket"
    )


# ------------------------------------------------------------------------------ tables, extraction
def _tables_native(p: Payload) -> str:
    run = _m(p, "by_method", "native")
    return (
        f"{pct(run['row_count_exact_rate'])} / {pct(run['cell_accuracy'])} "
        f"({run['documents']} documents)"
    )


def _tables_scanned(p: Payload) -> str:
    run = _m(p, "by_method", "scanned (re-rendered)")
    return f"{dec(run['row_recall'])} / {pct(run['cell_accuracy'])} ({run['documents']} documents)"


def _fields(method: str) -> Callable[[Payload], str]:
    def render(p: Payload) -> str:
        run = _m(p, "by_method", method)
        fields = run["all_fields"]
        return (
            f"{pct(fields['exact_match'])} / {pct(fields['normalized_match'])} / "
            f"{dec(fields['f1'])} ({run['documents']} documents)"
        )

    return render


def _line_items_scanned(p: Payload) -> str:
    lines = _m(p, "by_method", "scanned (re-rendered)", "line_items")
    return f"{dec(lines['row_recall'])} / {pct(lines['cell_accuracy'])} (rows paired by SKU)"


def _auto_native(p: Payload) -> str:
    run = _m(p, "by_method", "native")
    routing = run["routing"]
    return (
        f"{pct(routing['auto_share'])} / {pct(routing['error_rate_in_auto'])} "
        f"({routing['levels']['AUTO']} of {run['documents']})"
    )


def _auto_scanned(p: Payload) -> str:
    routing = _m(p, "by_method", "scanned (re-rendered)", "routing")
    levels = routing["levels"]
    return (
        f"{pct(routing['auto_share'])} ({levels['ANALYST_REVIEW']} to analyst review, "
        f"{levels['MANDATORY_REVIEW']} to mandatory review)"
    )


def _consistency(p: Payload) -> str:
    checks = _m(p, "consistency_checks")
    wrong = checks["printed total wrong"]
    misread = checks["printed document consistent (flag = misread)"]
    flagged = round(wrong["rate"] * wrong["documents"])
    false_flags = round(misread["rate"] * misread["documents"])
    return (
        f"{flagged} of {wrong['documents']} / {pct(misread['rate'])} "
        f"({false_flags} of {misread['documents']})"
    )


def _calibration(p: Payload) -> str:
    calibration = _m(p, "calibration")
    fields = calibration["development"]["all"]["fields"]
    chosen = calibration["chosen_threshold"]
    held = next(
        row for row in calibration["held_out"]["all"]["sweep"] if row["threshold"] == chosen
    )
    return (
        f"field ECE {dec(fields['ece'])} ({pct(fields['overconfident_share'])} of fields in "
        f"over-confident bins); threshold chosen on development {chosen:.2f} "
        f"(configured {calibration['current_threshold']:.2f}); held-out at it: "
        f"{held['auto']} of {held['documents']} auto-accepted, {held['errors']} errors "
        f"(95% bound {pct(held['error_upper_95'])})"
    )


# ------------------------------------------------------------------------------ discrepancies
def _pairs(run: Mapping[str, Any]) -> str:
    return f"{pct(run['precision'])} / {pct(run['recall'])}"


def _discrepancies_generated(p: Payload) -> str:
    run = _m(p, "as generated")
    fail = run["fail"]["pairs"]
    planted = fail["tp"] + fail["fn"]
    clean_fail = run["fail"]["routing"]["defect_free_documents_flagged"]["rate"]
    clean_warn = run["fail_or_warn"]["routing"]["defect_free_documents_flagged"]["rate"]
    return (
        f"{_pairs(fail)} ({planted} planted findings in {run['documents']} documents); "
        f"defect-free documents failing a rule {pct(clean_fail)}, with a warning "
        f"{pct(clean_warn)}"
    )


def _discrepancies_scanned(p: Payload) -> str:
    run = _m(p, "all scanned")
    return (
        f'FAIL {_pairs(run["fail"]["pairs"])}; FAIL or "could not be verified" '
        f"{_pairs(run['fail_or_warn']['pairs'])}"
    )


def _discrepancies_clean_scanned(p: Payload) -> str:
    run = _m(p, "all scanned")
    clean = run["fail"]["routing"]["defect_free_documents_flagged"]
    either = run["fail_or_warn"]["routing"]["defect_free_documents_flagged"]
    review = run["extraction_review"]["defect_free_documents"]["rate"]
    return (
        f"{pct(clean['rate'])} FAIL, {pct(either['rate'])} FAIL or warning "
        f"({pct(review)} are in review anyway for extraction uncertainty)"
    )


def _duplicates(p: Payload) -> str:
    parts = []
    for name in ("as generated", "all scanned"):
        duplicates = _m(p, name, "duplicates")
        strong = duplicates["strong"]
        parts.append(
            f"{name}: {strong['tp']} of {duplicates['resent_invoices']}, {strong['fp']} wrong pairs"
        )
    return "; ".join(parts)


def _versions(p: Payload) -> str:
    parts = []
    for name in ("native", "scanned (re-rendered)"):
        run = _m(p, name)
        parts.append(f"{name}: {round(run['steps_exact'] * run['steps'])} of {run['steps']}")
    return f"{'; '.join(parts)} version steps exactly right ({p['dataset']['families']} families)"


# ------------------------------------------------------------------------------ retrieval, search
HYBRID = "hybrid (production: ts_rank_cd order)"


def _retrieval(p: Payload) -> str:
    parts = []
    for name, label in (("kb-queries", "tuning set"), ("kb-queries-holdout", "holdout")):
        run = _m(p, "configs", HYBRID, name)
        answerable = _m(p, "gate", name, "answerable")
        parts.append(
            f"{name} ({label}, {answerable} answerable): {pct(run['hit@1'])} / "
            f"{pct(run['hit@5'])} / {dec(run['mrr'])} / {dec(run['ndcg@5'])}"
        )
    return " · ".join(parts) + f" — {p['config']['embedding_model']} embeddings"


ABLATIONS = (
    ("full text only (production: IDF order)", "full text only"),
    ("dense only (hashing)", "dense only (hashing)"),
    ("hybrid, no title/breadcrumb prefix", "no title/breadcrumb prefix"),
    ("hybrid, fixed-size chunks", "fixed-size chunks"),
)


def _ablations(p: Payload) -> str:
    return (
        ", ".join(
            f"{label} {dec(_m(p, 'configs', config, 'kb-queries', 'mrr'))}"
            for config, label in ABLATIONS
        )
        + f" (hybrid {dec(_m(p, 'configs', HYBRID, 'kb-queries', 'mrr'))})"
    )


def _evidence_gate(p: Payload) -> str:
    parts = []
    for name in ("kb-queries", "kb-queries-holdout"):
        gate = _m(p, "gate", name)
        parts.append(
            f"{name} {gate['correctly_refused']} of {gate['unanswerable']} / "
            f"{gate['false_refusals']} of {gate['answerable']}"
        )
    return " · ".join(parts)


def _retrieval_scope(p: Payload) -> str:
    access, versions = _m(p, "access_control"), _m(p, "versions")
    return (
        f"{access['passages_from_other_departments']} "
        f"({access['questions_as_finance_user']} questions as a Finance user) / "
        f"{versions['superseded_passages_on_eval_date']}"
    )


def _retrieval_latency(p: Payload) -> str:
    latency = _m(p, "latency_ms")
    passages = p["dataset"]["corpora"]["sections"]["chunks"]
    return f"{ms(latency['p50'])} / {ms(latency['p95'])} ({passages} passages)"


STRUCTURED_FAMILIES = ("vendor", "payment terms", "totals", "dates", "types")


def _search_structured(p: Payload) -> str:
    families = _m(p, "families")
    tp = sum(families[name]["tp"] for name in STRUCTURED_FAMILIES)
    precision = min(families[name]["precision"] for name in STRUCTURED_FAMILIES)
    recall = min(families[name]["recall"] for name in STRUCTURED_FAMILIES)
    questions = sum(1 for q in _m(p, "questions") if q["family"] in STRUCTURED_FAMILIES)
    return (
        f"{pct(precision)} / {pct(recall)} (lowest family; {questions} questions, "
        f"{tp} relevant documents found)"
    )


def _search_text(p: Payload) -> str:
    text = _m(p, "families", "text")
    questions = sum(1 for q in _m(p, "questions") if q["family"] == "text")
    return f"{pct(text['recall'])} / {pct(text['precision'])} ({questions} line-item queries)"


# ------------------------------------------------------------------------------ agent
def _agent_success(p: Payload) -> str:
    dev, held = _m(p, "development"), _m(p, "held-out")
    return (
        f"development ({dev['runs']} runs): {pct(dev['task_success']['named'])} / "
        f"{pct(dev['task_success']['search'])} / {pct(dev['task_success']['policy'])} · "
        f"held-out, seed {p['dataset']['held_out_seed']} ({held['runs']} runs): "
        f"{pct(held['task_success']['named'])} / {pct(held['task_success']['search'])}"
    )


def _agent_safety(p: Payload) -> str:
    return " · ".join(
        f"{name}: {run['unsafe_recommendations']} / {pct(run['defect_detection'])} / "
        f"{run['false_failures_on_clean_invoices']}"
        for name, run in ((n, _m(p, n)) for n in ("development", "held-out"))
    )


def _agent_tools(p: Payload) -> str:
    return " · ".join(
        f"{name}: {pct(run['tool_selection']['precision'])} / "
        f"{pct(run['tool_selection']['recall'])}; {run['grounding']['with_valid_evidence']} of "
        f"{run['grounding']['findings_citing_evidence']}"
        for name, run in ((n, _m(p, n)) for n in ("development", "held-out"))
    )


def _agent_policy(p: Payload) -> str:
    return " · ".join(
        f"{name} {pct(_m(p, name, 'grounding', 'governing_policy_retrieved'))}"
        for name in ("development", "held-out")
    )


def _agent_guardrails(p: Payload) -> str:
    guard = _m(p, "development", "guardrails")
    return (
        f"{guard['adversarial_runs']} defective invoices per dataset: "
        f"{guard['unsafe_recommendations_accepted']} payment recommendations accepted, "
        f"{guard['adversarial_statements_kept']} adversarial statements and "
        f"{guard['adversarial_summaries_kept']} summaries kept"
    )


# ------------------------------------------------------------------------------ workflows
INVOICE_SETS = ("invoices (development)", "invoices (held-out)")


def _workflow_correct(p: Payload) -> str:
    invoices = " + ".join(str(_m(p, name, "workflows")) for name in INVOICE_SETS)
    invoice_rate = min(_m(p, name, "correct") for name in INVOICE_SETS)
    contracts = _m(p, "contracts")
    return (
        f"{pct(invoice_rate)} of {invoices} invoices (seeds "
        f"{p['dataset']['invoice_development_seed']} and {p['dataset']['invoice_held_out_seed']}) "
        f"/ {pct(contracts['correct'])} of {contracts['workflows']} contract versions "
        f"({p['dataset']['contract_families']} families, seed {p['dataset']['contract_seed']})"
    )


ALL_WORKFLOW_SETS = (*INVOICE_SETS, "contracts")


def _workflow_unsafe(p: Payload) -> str:
    return str(sum(_m(p, name, "unsafe_proposals") for name in ALL_WORKFLOW_SETS))


def _maker_checker(p: Payload) -> str:
    refused = sum(_m(p, name, "maker_checker", "refused") for name in ALL_WORKFLOW_SETS)
    attempts = sum(_m(p, name, "maker_checker", "attempts") for name in ALL_WORKFLOW_SETS)
    bypasses = sum(_m(p, name, "maker_checker", "bypasses") for name in ALL_WORKFLOW_SETS)
    audited = min(_m(p, name, "maker_checker", "refusals_audited") for name in ALL_WORKFLOW_SETS)
    return (
        f"{refused} of {attempts} (through the service and by direct table writes) / "
        f"{bypasses}; refusals audited: {pct(audited)}"
    )


def _workflow_audit(p: Payload) -> str:
    events = sum(_m(p, name, "audit", "events") for name in ALL_WORKFLOW_SETS)
    transitions = sum(_m(p, name, "audit", "transitions") for name in ALL_WORKFLOW_SETS)
    return f"{events} of {transitions}"


def _workflow_reports(p: Payload) -> str:
    verified = min(_m(p, n, "reports", "workflow_report_verified") for n in ALL_WORKFLOW_SETS)
    identical = min(_m(p, n, "reports", "regenerated_identical") for n in ALL_WORKFLOW_SETS)
    return f"{pct(verified)} / {pct(identical)} of finished workflows"


def _contract_rules(p: Payload) -> str:
    contracts = _m(p, "contracts")
    changes = contracts["version_changes"]
    exact = round(changes["exact"] * changes["steps"])
    return (
        f"{contracts['rules']['correct']} of {contracts['rules']['scored']} rule outcomes; "
        f"version comparison step exactly right on {exact} of {changes['steps']} steps"
    )


# ------------------------------------------------------------------------------ system
def _throughput(p: Payload) -> str:
    one, four = _m(p, "pipeline", "1_claim_loops"), _m(p, "pipeline", "4_claim_loops")
    return (
        f"{one['documents_per_minute']:.1f} / {four['documents_per_minute']:.1f} documents per "
        f"minute ({one['documents']} documents, {p['dataset']['scanned']} scanned; "
        f"{p['environment']['cpus']} CPUs)"
    )


def _processing_time(p: Payload) -> str:
    processing = _m(p, "pipeline", "1_claim_loops", "processing_seconds")
    native, scanned = processing["native"], processing["scanned"]
    return (
        f"native {seconds(native['p50'])} / {seconds(native['p95'])} · "
        f"scanned {seconds(scanned['p50'])} / {seconds(scanned['p95'])}"
    )


def _failures(p: Payload) -> str:
    runs = _m(p, "pipeline")
    failed = sum(run["failed"] for run in runs.values())
    retried = sum(run["retried"] for run in runs.values())
    documents = sum(run["documents"] for run in runs.values())
    return f"{failed} failed / {retried} retried of {documents} jobs"


def _api_latency(p: Payload) -> str:
    api = _m(p, "api_ms")
    concurrent = api["inbox_concurrent"]
    return (
        f"inbox {ms(api['inbox']['p95'])}, document {ms(api['document']['p95'])}, "
        f"dashboard {ms(api['dashboard']['p95'])}, search {ms(api['search']['p95'])}; "
        f"inbox with {concurrent['clients']} clients {ms(concurrent['p95'])} "
        f"({concurrent['requests_per_second']:.0f} requests/s)"
    )


